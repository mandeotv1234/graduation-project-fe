'use client'

import { useCallback, useMemo, useState } from 'react'

import {
  BLOCK_REGISTRY,
  type ExamBlock,
  type SqlDdlBlock,
  type SqlDmlBlock
} from '../components/common-part-blocks'
import {
  resolveScriptToRun,
  type ExistingScriptOption,
  type ScriptSourceMode
} from '../components/common-part-export.domain'
import { exportDatasetsFromScript } from '../components/common-part-export.usecase'
import type { ExecuteSqlResponse } from '@/lib/types'
import { toast } from 'sonner'

interface UseDatasetExportOptions {
  blocks: ExamBlock[]
  executeSqlInExam: (sql: string) => Promise<ExecuteSqlResponse | undefined>
  setBlocks: React.Dispatch<React.SetStateAction<ExamBlock[]>>
}

export function useDatasetExport({
  blocks,
  executeSqlInExam,
  setBlocks
}: UseDatasetExportOptions) {
  const [isDatasetDialogOpen, setIsDatasetDialogOpen] = useState(false)
  const [datasetScriptMode, setDatasetScriptMode] =
    useState<ScriptSourceMode>('existing')
  const [selectedDatasetScriptId, setSelectedDatasetScriptId] = useState('')
  const [customDatasetScript, setCustomDatasetScript] = useState('')
  const [isExportingDatasets, setIsExportingDatasets] = useState(false)

  const existingScriptOptions = useMemo<ExistingScriptOption[]>(
    () =>
      blocks
        .filter(
          (block): block is SqlDdlBlock | SqlDmlBlock =>
            (block.kind === 'sql-ddl' || block.kind === 'sql-dml') &&
            block.data.sql.trim().length > 0
        )
        .map((block) => ({
          id: block.id,
          title: block.title,
          sql: block.data.sql,
          kind: block.kind
        })),
    [blocks]
  )

  const datasetScriptOptions = useMemo(() => {
    const dmlOnly = existingScriptOptions.filter(
      (item) => item.kind === 'sql-dml'
    )
    return dmlOnly.length > 0 ? dmlOnly : existingScriptOptions
  }, [existingScriptOptions])

  const openDatasetExportDialog = useCallback(() => {
    const defaultOption = datasetScriptOptions[0]
    setDatasetScriptMode(defaultOption ? 'existing' : 'custom')
    setSelectedDatasetScriptId(defaultOption?.id ?? '')
    setIsDatasetDialogOpen(true)
  }, [datasetScriptOptions])

  const exportDatasetsToCommonPart = useCallback(async () => {
    const sql = resolveScriptToRun(
      datasetScriptMode,
      selectedDatasetScriptId,
      customDatasetScript,
      datasetScriptOptions
    )

    if (!sql) {
      toast.error('Vui lòng chọn script hoặc nhập script SQL để chạy')
      return
    }

    const ddlBlock = blocks.find(
      (block): block is SqlDdlBlock => block.kind === 'sql-ddl'
    )
    const existingDdl = ddlBlock?.data.sql?.trim() ?? ''

    setIsExportingDatasets(true)
    const result = await exportDatasetsFromScript(
      sql,
      existingDdl,
      executeSqlInExam
    )

    setIsExportingDatasets(false)

    if ('errorMessage' in result) {
      toast.error(result.errorMessage)
      return
    }

    const exportedBlocks: SqlDmlBlock[] = result.datasets.map((dataset) => {
      const dmlBlock = BLOCK_REGISTRY.find(
        (item) => item.kind === 'sql-dml'
      )?.createBlock() as SqlDmlBlock

      dmlBlock.title = dataset.title
      dmlBlock.data.sql = dataset.sql
      dmlBlock.data.tableData = dataset.tableData
      dmlBlock.data.displayMode = 'data'
      dmlBlock.visibleToStudent = true

      return dmlBlock
    })

    setBlocks((prev) => {
      const withoutAutoGeneratedDml = prev.filter((block) => {
        if (block.kind !== 'sql-dml') {
          return true
        }

        return !/Dữ\s+liệu\s+tự\s+động/i.test(block.title)
      })

      return [...withoutAutoGeneratedDml, ...exportedBlocks]
    })

    setIsDatasetDialogOpen(false)
    toast.success(
      `Đã xuất ${exportedBlocks.length} bảng dữ liệu vào phần đề chung`
    )
  }, [
    datasetScriptMode,
    selectedDatasetScriptId,
    customDatasetScript,
    datasetScriptOptions,
    blocks,
    executeSqlInExam,
    setBlocks
  ])

  return {
    isDatasetDialogOpen,
    setIsDatasetDialogOpen,
    datasetScriptMode,
    setDatasetScriptMode,
    selectedDatasetScriptId,
    setSelectedDatasetScriptId,
    customDatasetScript,
    setCustomDatasetScript,
    isExportingDatasets,
    datasetScriptOptions,
    openDatasetExportDialog,
    exportDatasetsToCommonPart
  }
}
